/* Visual and accessible interaction checks, synthetic account responses only. */
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = process.env.MEMBERSHIP_TEST_APP_URL || 'http://127.0.0.1:8487'
const output = path.resolve(__dirname, '../../.local/frontend-reference-design')
const checks = [], errors = []
async function check(name, action) { await action(); checks.push(name); console.log('PASS ' + name) }
async function capture(page, name, fullPage=false) {
  await page.waitForFunction(() => [...document.querySelectorAll('dialog:modal')].every(dialog => getComputedStyle(dialog).opacity === '1'))
  await page.screenshot({path:path.join(output,name),fullPage,animations:'disabled'})
}
const quota = member => ({ email:'design@example.com', simulated:true, order:null, quota:{ limit:member ? 30 : 3, used:1, reserved:0, remaining:member ? 29 : 2, member_expires:member ? Date.now()/1000+86400*30 : null, day:'2026-10-08' } })
const fulfill = (route, json, status=200) => route.fulfill({status, contentType:'application/json', body:JSON.stringify(json)})
;(async () => {
  await fs.mkdir(output, {recursive:true})
  const browser = await chromium.launch({channel:'msedge', headless:true})
  const context = await browser.newContext({viewport:{width:1440,height:960}, reducedMotion:'reduce'})
  const page = await context.newPage()
  let account = null, checkoutRequests = 0
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/api/v1/account/*', async route => {
    const endpoint = new URL(route.request().url()).pathname.split('/').at(-1)
    if (endpoint === 'config') return fulfill(route,{enabled:true})
    if (endpoint === 'settings') return fulfill(route,{enabled:true, verification_required:false, mail_delivery:'local_file',simulated:true})
    if (endpoint === 'me' || endpoint === 'refresh') return fulfill(route,account || {detail:{code:'LOGIN_REQUIRED',message:'请先登录。'}},account ? 200 : 401)
    if (endpoint === 'login') { account=quota(false); return fulfill(route,{message:'已登录。'}) }
    if (endpoint === 'logout') { account=null; return fulfill(route,{message:'已退出。'}) }
    if (endpoint === 'checkout') { checkoutRequests++; return fulfill(route,{detail:{code:'TEST_GUARD',message:'视觉测试不创建付款。'}},409) }
    return route.abort()
  })
  try {
    await page.goto(base, {waitUntil:'networkidle'})
    await check('homepage shows blue hero and accurate two-plan pricing without unsupported promises', async () => {
      await page.locator('#pricing').waitFor()
      assert.equal(await page.locator('#pricing .membership-plan').count(),2)
      const text=await page.locator('#pricing').innerText()
      assert.match(text,/19\.90/); assert.match(text,/每日 3 次/); assert.match(text,/每日 30 次/)
      assert.doesNotMatch(text,/1800|无限次 AI|¥9\.9|专属客服|限时优惠/)
      await capture(page,'home-desktop.png')
      await page.locator('.home-navigation').getByRole('link',{name:'套餐价格'}).click()
      await capture(page,'plans-desktop.png')
    })
    await check('guest plan opens compact login without creating a checkout', async () => {
      await page.locator('#pricing').getByRole('button',{name:'查看会员方案'}).click()
      await page.getByRole('heading',{name:'登录账号',exact:true}).waitFor()
      const modal=page.locator('dialog:modal')
      const bounds=await modal.boundingBox()
      assert.ok(bounds.width<=480 && bounds.width>400)
      assert.equal(await modal.locator('.membership-plans').count(),0)
      await capture(page,'login-desktop.png')
      assert.equal(checkoutRequests,0)
    })
    await check('password visibility is accessible and returns to hidden when switching forms', async () => {
      const password=page.getByLabel('密码',{exact:true})
      await password.fill('fake-design-password-long')
      await page.getByRole('button',{name:'显示密码',exact:true}).click()
      assert.equal(await password.getAttribute('type'),'text')
      await page.getByRole('button',{name:'隐藏密码',exact:true}).click()
      assert.equal(await password.getAttribute('type'),'password')
      await page.getByRole('button',{name:'注册',exact:true}).click()
      await page.getByRole('heading',{name:'创建账号',exact:true}).waitFor()
      assert.equal(await page.getByLabel('密码',{exact:true}).inputValue(),'')
      assert.equal(await page.getByLabel('密码',{exact:true}).getAttribute('minlength'),'12')
      await capture(page,'register-desktop.png')
      await page.locator('dialog:modal').getByRole('button',{name:'登录',exact:true}).click()
    })
    await check('modal traps keyboard focus and Escape restores the triggering control', async () => {
      await page.getByRole('button',{name:'关闭弹窗',exact:true}).focus()
      await page.keyboard.press('Shift+Tab')
      const within=await page.evaluate(()=>!!document.activeElement?.closest('dialog:modal'))
      assert.equal(within,true)
      await page.keyboard.press('Escape')
      assert.equal(await page.locator('dialog:modal').count(),0)
      await page.locator('#pricing').getByRole('button',{name:'查看会员方案'}).focus()
      await page.keyboard.press('Enter')
      await page.keyboard.press('Escape')
      assert.equal(await page.evaluate(()=>document.activeElement?.textContent.trim()),'查看会员方案')
    })
    for (const width of [390,320]) {
      await page.setViewportSize({width,height:844})
      await page.goto(base,{waitUntil:'networkidle'})
      await check('homepage and pricing fit narrow viewport ' + width, async () => {
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
        await capture(page,'home-'+width+'.png',true)
        await page.locator('#pricing').scrollIntoViewIfNeeded()
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
      })
      await check('auth modal fits narrow viewport and email has its own accessible label ' + width, async () => {
        await page.getByRole('button',{name:'登录',exact:true}).click()
        await page.getByLabel('邮箱',{exact:true}).fill('design@example.com')
        const box=await page.locator('dialog:modal').boundingBox()
        assert.ok(box.x>=0 && box.x+box.width<=width && box.y>=0 && box.y+box.height<=844)
        await capture(page,'login-'+width+'.png')
        await page.keyboard.press('Escape')
      })
    }
    await page.setViewportSize({width:1440,height:960})
    await page.goto(base,{waitUntil:'networkidle'})
    await page.getByRole('button',{name:'登录',exact:true}).click()
    await page.getByLabel('邮箱',{exact:true}).fill('design@example.com')
    await page.getByLabel('密码',{exact:true}).fill('fake-design-password-long')
    await page.getByRole('button',{name:'登录账号',exact:true}).click()
    await page.getByText('design@example.com · 普通用户',{exact:true}).waitFor()
    await check('signed-in account shows server quota and opens the avatar menu', async () => {
      await page.getByText('今日已用 1 / 3 次').waitFor()
      await capture(page,'account-desktop.png')
      await page.keyboard.press('Escape')
      await page.getByRole('button',{name:'账号 · 普通用户',exact:true}).click()
      await page.locator('.member-dropdown').waitFor()
      await capture(page,'account-menu.png')
      await page.locator('.member-dropdown').getByRole('button',{name:'账号与会员',exact:true}).focus()
      await page.keyboard.press('Escape')
      assert.equal(await page.locator('.member-dropdown').count(),0)
      assert.equal(await page.getByRole('button',{name:'账号 · 普通用户',exact:true}).evaluate(button=>button===document.activeElement),true)
      await page.getByRole('button',{name:'账号 · 普通用户',exact:true}).click()
      await page.locator('.member-dropdown').getByRole('button',{name:'账号与会员',exact:true}).click()
      await page.getByRole('heading',{name:'账号与会员',exact:true}).waitFor()
      await page.keyboard.press('Escape')
      assert.equal(await page.getByRole('button',{name:'账号 · 普通用户',exact:true}).evaluate(button=>button===document.activeElement),true)
    })
    account=quota(true)
    await page.reload({waitUntil:'networkidle'})
    await check('VIP badge follows server status and active membership blocks purchase', async () => {
      await page.getByRole('button',{name:'VIP',exact:true}).click()
      await page.getByText('design@example.com · 会员',{exact:true}).waitFor()
      assert.equal(await page.getByRole('button',{name:'会员已开通',exact:true}).isDisabled(),true)
      assert.equal(await page.locator('.member-panel .membership-price strong').last().innerText(),'¥19.90')
      await capture(page,'vip-desktop.png')
      await page.keyboard.press('Escape')
      await page.getByRole('button',{name:'会员中心',exact:true}).click()
      await page.locator('.member-dropdown').getByText(/VIP 会员/).waitFor()
      await capture(page,'vip-menu.png')
      await page.locator('.workspace-intro').click()
      assert.equal(await page.locator('.member-dropdown').count(),0)
    })
    await check('VIP dialog and dropdown fit 320 px and logout clears status', async () => {
      await page.setViewportSize({width:320,height:844})
      await page.getByRole('button',{name:'VIP',exact:true}).click()
      await capture(page,'vip-mobile.png')
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
      await page.keyboard.press('Escape')
      await page.getByRole('button',{name:'会员中心',exact:true}).click()
      const menu=await page.locator('.member-dropdown').boundingBox()
      assert.ok(menu.x>=0 && menu.x+menu.width<=320)
      await page.locator('.member-dropdown').getByRole('button',{name:'退出登录',exact:true}).click()
      await page.getByRole('button',{name:'登录',exact:true}).waitFor()
      assert.equal(await page.locator('.member-dropdown').count(),0)
      assert.equal(await page.locator('.member-vip-active').count(),0)
    })
    await check('visual interactions have no checkout requests or browser errors', async()=>{ assert.equal(checkoutRequests,0); assert.deepEqual(errors,[]) })
  } finally {
    await fs.writeFile(path.join(output,'report.json'),JSON.stringify({checks,errors,checkoutRequests,simulation:true},null,2))
    console.log(JSON.stringify({passed:checks.length,errors,checkoutRequests}))
    await browser.close()
  }
})().catch(error=>{console.error(error.stack);process.exitCode=1})
